export function 주제판별({ 주제명 = "", 키워드 = "" } = {}) {
  const 명시 = String(주제명).trim();
  if (/정부|정책|복지|공공/.test(명시)) return 주제.정부정책;
  if (/스타|연예|방송|이슈/.test(명시)) return 주제.스타이슈;
  return /(지원|보조금|복지|연금|바우처|장려금|수당|급여|환급|감면|정책|공고|신청|발급|상생카드|지역화폐|주택|보험|돌봄|의료|교육|교통)/.test(String(키워드))
    ? 주제.정부정책 : 주제.스타이슈;
}

export function 사진수결정(주제명, 요청사진수) {
  if (주제명 === 주제.스타이슈) return 0;
  return 요청사진수 == null ? 3 : Number(요청사진수);
}

